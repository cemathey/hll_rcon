# TODO: Include map images in the package and add property to the path for it
class Map(BaseModel):
    """Models a base HLL map before game mode/environment/etc."""

    id: str
    pretty_name: str
    orientation: MapOrientations
    allies: Factions
    axis: Factions
    allies_hq_sector: int

    @property
    def axis_hq_sector(self) -> int:
        return 1 if self.allies_hq_sector == 5 else 5


class Layer(BaseModel):
    """Models a HLL map as played on the game server (environment, game mode, etc.)"""

    id: str
    map: Map
    game_mode: GameMode
    environment: MapEnvironments
    attackers: Teams | None = Field(default=None)

    def __repr__(self):
        return f"Layer(id={self.id}, )"


